/**
 * The registry is only worth having if it is *true*.
 *
 * A list of worlds that quietly disagrees with the router is worse than no list
 * at all: it renders a card, the card navigates, and the visitor lands on the
 * 404. That is not hypothetical — the hub shipped a "Healdsburg Village" card
 * pointing at "/" for weeks after "/" stopped being the village, and nothing
 * caught it because nothing was checking.
 *
 * So these tests read the actual sources — the router, the pages, the Terminal's
 * gates — and check the registry against them rather than against another copy
 * of the same assumptions.
 */
import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import {
  WORLDS,
  CHROMELESS_ROUTES,
  PASSPORT_ROUTES,
  routesOf,
  worldByRoute,
} from "@/worlds/registry";
import { WORLD_ART } from "@/worlds/art";
import { GATES } from "@/terminal/geo/terminalGeo";

const SRC = join(process.cwd(), "src");
const appSource = readFileSync(join(SRC, "App.tsx"), "utf8");

/**
 * Every route App.tsx mentions.
 *
 * Matching `path="…"` alone is not enough — the Vibeverse's three routes are
 * generated by mapping over an array literal, so they never appear next to the
 * word `path`. Any quoted string starting with "/" in this file is a route:
 * module specifiers all start with "." or "@", and the only other "/" strings
 * are `Navigate to=` targets, which are routes too.
 */
const declaredRoutes = new Set(
  [...appSource.matchAll(/"(\/[^"]*)"/g)].map((m) => m[1]),
);

/** Text of every page, concatenated — enough to check a hook is called. */
const pageSources = readdirSync(join(SRC, "pages"))
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => readFileSync(join(SRC, "pages", f), "utf8"))
  .join("\n");

describe("the registry", () => {
  it("gives every world a unique key and a unique route", () => {
    const keys = WORLDS.map((w) => w.key);
    expect(new Set(keys).size, "duplicate key").toBe(keys.length);

    const routes = WORLDS.flatMap(routesOf);
    expect(new Set(routes).size, "two worlds claim the same route").toBe(routes.length);
  });

  it("points every world at a route the router actually serves", () => {
    for (const w of WORLDS) {
      for (const route of routesOf(w)) {
        // Query strings are a world's spawn point, not a route of their own:
        // `/city?spawn=ski` is served by `/city`.
        const path = route.split("?")[0];
        expect(declaredRoutes.has(path), `${w.key} → ${route}`).toBe(true);
      }
    }
  });

  it("does not send a world to the page it is already on", () => {
    /* The bug this encodes: "/" is the hub. A world whose route is "/" is a
       card on the hub that reloads the hub. */
    for (const w of WORLDS) expect(w.route, w.key).not.toBe("/");
  });

  it("keys card art off worlds that exist", () => {
    const keys = new Set(WORLDS.map((w) => w.key));
    for (const key of Object.keys(WORLD_ART)) {
      expect(keys.has(key), `art for unknown world "${key}"`).toBe(true);
    }
  });
});

describe("the passport", () => {
  it("stamps only worlds whose page actually calls useWorldStamp", () => {
    /* Redline is the exception and it is deliberate: it has no page, and it is
       stamped by holding the ground. See lib/passport.ts. */
    for (const { route } of PASSPORT_ROUTES) {
      if (route.startsWith("/vibeverse/")) continue;
      expect(
        pageSources.includes(`useWorldStamp("${route}"`),
        `${route} is in the passport but no page stamps it`,
      ).toBe(true);
    }
  });

  it("has a page for every world that stamps one", () => {
    const stamped = [...pageSources.matchAll(/useWorldStamp\("([^"]+)"/g)].map((m) => m[1]);
    const known = new Set(PASSPORT_ROUTES.map((p) => p.route));
    for (const route of stamped) {
      expect(known.has(route), `${route} stamps a page the passport does not list`).toBe(
        true,
      );
    }
  });
});

describe("fullscreen worlds", () => {
  it("hides the app chrome on every URL a world answers on", () => {
    /* Arriving by an alias must not hand you a nav bar sitting on the
       crosshair — /fps and /san-palmas are the same shooter. */
    const chromeless = new Set(CHROMELESS_ROUTES);
    for (const w of WORLDS.filter((x) => x.chromeless)) {
      for (const route of routesOf(w)) {
        expect(chromeless.has(route), `${route} keeps the nav`).toBe(true);
      }
    }
  });
});

describe("the Terminal's gates", () => {
  it("only opens onto worlds the registry knows", () => {
    for (const gate of GATES) {
      const world = worldByRoute(gate.to);
      expect(world, `gate "${gate.key}" → ${gate.to} is not a registered world`).toBeTruthy();
      /* Keys have to line up too — the gate's art is looked up by key, and a
         gate keyed to nothing renders a blank card over a real island. */
      expect(world!.key, `gate "${gate.key}" name/key drift`).toBe(gate.key);
    }
  });
});

/**
 * The running order at the top of `registry.ts` is the knob people actually
 * reach for, and it is a list of loose strings — so a renamed key does not
 * error, it silently drops that world to the bottom of every surface in the
 * app. That is a hard thing to notice and an easy thing to check.
 */
describe("the running order", () => {
  const registrySource = readFileSync(join(SRC, "worlds/registry.ts"), "utf8");
  const order = [
    ...registrySource
      .slice(registrySource.indexOf("const ORDER: string[] = ["))
      .slice(0, registrySource.slice(registrySource.indexOf("const ORDER")).indexOf("];"))
      .matchAll(/"([a-z0-9-]+)"/g),
  ].map((m) => m[1]);

  it("was found at all", () => {
    expect(order.length).toBeGreaterThan(10);
  });

  it("names only worlds that exist", () => {
    const keys = new Set(WORLDS.map((w) => w.key));
    const ghosts = order.filter((k) => !keys.has(k));
    expect(ghosts, `ORDER lists keys no world has: ${ghosts.join(", ")}`).toEqual([]);
  });

  it("names each world at most once", () => {
    const seen = new Set<string>();
    const dupes = order.filter((k) => (seen.has(k) ? true : (seen.add(k), false)));
    expect(dupes).toEqual([]);
  });

  it("actually drives what WORLDS returns", () => {
    // The first few keys of ORDER must be the first few worlds, in that order.
    expect(WORLDS.slice(0, order.length).map((w) => w.key).slice(0, 4))
      .toEqual(order.slice(0, 4));
  });

  it("opens on Vibe Island", () => {
    // Not arbitrary: it is the gentlest door, it works on a phone, and it is
    // the one to put in front of somebody who has never been here.
    expect(WORLDS[0].key).toBe("island");
  });
});
